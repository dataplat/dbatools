// Port of public/Get-DbaDump.ps1 at refs/pins/dbatools-2026-10-22: the rows of sys.dm_server_memory_dumps on the connection of each instance from SQL Server 2008 R2 on.
/// <summary>Retrieves SQL Server memory dump file information from sys.dm_server_memory_dumps DMV.</summary>
/// <para>
/// Queries the sys.dm_server_memory_dumps dynamic management view to return details about memory dump files (.mdmp) generated by SQL Server. Memory dumps are created when SQL Server encounters crashes, assertion failures, or other critical errors that require investigation. This function helps DBAs quickly identify when dumps have been generated, their size, and creation time, which is essential for troubleshooting server stability issues and working with Microsoft Support for crash analysis.
/// </para>
/// <example>
/// <code>
/// PS C:\&gt; Get-DbaDump -SqlInstance sql2016
/// </code>
/// <para>
/// Shows the detailed information for memory dump(s) located on sql2016 instance
/// </para>
/// </example>
/// <example>
/// <code>
/// PS C:\&gt; Get-DbaDump -SqlInstance sql2016 -SqlCredential sqladmin
/// </code>
/// <para>
/// Shows the detailed information for memory dump(s) located on sql2016 instance. Logs into the SQL Server using the SQL login 'sqladmin'
/// </para>
/// </example>
/// <list type="alertSet">
/// <item>
/// <term />
/// <description>
/// <para>
/// Tags: Diagnostic, Engine, Corruption
/// Author: Garry Bargsley (@gbargsley), blog.garrybargsley.com
/// </para>
/// <para>
/// Website: https://dbatools.io
/// Copyright: (c) 2018 by dbatools, licensed under MIT
/// License: MIT https://opensource.org/licenses/MIT
/// </para>
/// </description>
/// </item>
/// </list>
/// <seealso href="https://dbatools.io/Get-DbaDump" />
[Cmdlet(VerbsCommon.Get, "DbaDump")]
public sealed class GetDbaDumpCommand : DbaInstanceCmdlet
{
    private const string Sql = "SELECT filename, creation_time, size_in_bytes FROM sys.dm_server_memory_dumps";

    /// <para>
    /// The target SQL Server instance or instances. This can be a collection and receive pipeline input to allow the function to be executed against multiple SQL Server instances.
    /// </para>
    [Parameter(Mandatory = true, ValueFromPipeline = true, Position = 0)]
    public override DbaInstanceParameter[] SqlInstance { get; set; } = null!;

    /// <para>
    /// Login to the target instance using alternative credentials. Accepts PowerShell credentials (Get-Credential).
    /// </para>
    /// <para>
    /// Windows Authentication, SQL Server Authentication, Active Directory - Password, and Active Directory - Integrated are all supported.
    /// </para>
    /// <para>
    /// For MFA support, please use Connect-DbaInstance.
    /// </para>
    [Parameter(Position = 1)]
    public override PSCredential? SqlCredential { get; set; }

    // Overridden only to carry the pinned .PARAMETER EnableException help; same bare [Parameter] as the base.
    /// <para>
    /// By default, when something goes wrong we try to catch it, interpret it and give you a friendly warning message.
    /// This avoids overwhelming you with "sea of red" exceptions, but is inconvenient because it basically disables advanced scripting.
    /// Using this switch turns this "nice by default" feature off and enables you to catch exceptions with your own try/catch.
    /// </para>
    [Parameter]
    public override SwitchParameter EnableException { get; set; }

    protected override void ProcessRecord()
    {
        foreach (DbaInstanceParameter instance in SqlInstance)
        {
            // Correction azure-refusal: sys.dm_server_memory_dumps applies to SQL Server only (Microsoft Learn), so Azure SQL Database is refused at
            // connect, as Connect-DbaInstance -AzureUnsupported does, where the pin sent the query and reported the missing view.
            Server? server = ConnectInstance(instance, "Failure", azureUnsupported: true);
            if (server is null)
                continue;

            // The pin reads the version outside its try. No fault there showed in any case its pin measured on both editions (evidence/pin-dump2-20261104.txt), and none is proven
            // absent. No test reaches this refusal: every leg's instance is SQL Server 2017 or later.
            if (server.VersionMajor < 11 && !(server.VersionMajor == 10 && server.VersionMinor == 50))
            {
                StopFunction("This function does not support versions lower than SQL Server 2008 R2 (v10.50). Skipping server '" + instance + "'", continueLoop: true);
                continue;
            }

            string failureMessage = "Issue collecting data on " + server.ToString();

            DataTable? results;
            try
            {
                DataSet tables = server.ConnectionContext.ExecuteWithResults(Sql);
                results = tables.Tables.Count > 0 ? tables.Tables[0] : null;
            }
            catch (Exception failure) when (failure is not PipelineStoppedException)
            {
                StopFunction(failureMessage, target: server, errorRecord: QueryRecord(failure), continueLoop: true);
                continue;
            }

            if (results is null)
                continue;

            // PS: the row loop sits inside the same try, so a value [dbasize] cannot take ends this instance with that warning.
            try
            {
                foreach (DataRow row in results.Rows)
                {
                    PSObject output = new();
                    OutputHelper.AddInstanceProperties(output, server);
                    output.Properties.Add(new PSNoteProperty("FileName", row["filename"]));
                    output.Properties.Add(new PSNoteProperty("CreationTime", row["creation_time"]));
                    output.Properties.Add(new PSNoteProperty("Size", LanguagePrimitives.ConvertTo(row["size_in_bytes"], typeof(Size), CultureInfo.InvariantCulture)));
                    WriteObject(output);
                }
            }
            catch (Exception failure) when (failure is not PipelineStoppedException)
            {
                StopFunction(failureMessage, target: server, errorRecord: new ErrorRecord(failure, "dbatools_Get-DbaDump", ErrorCategory.NotSpecified, null), continueLoop: true);
            }
        }
    }

    // PS: $_ for a failed $server.Query: the script method's catch joins the messages of the exception chain and throws that
    // text, which the method call reports as "Exception calling "Query" ...". As the pin measured, evidence/pin-dump2-20261104.txt, low-login-ee.
    private static ErrorRecord QueryRecord(Exception failure)
    {
        StringBuilder joined = new();
        for (Exception? current = failure; current is not null; current = current.InnerException)
            joined.Append(current.Message);
        string message = joined.ToString();
        MethodInvocationException call = new(String.Format(CultureInfo.InvariantCulture,
            "Exception calling \"Query\" with \"1\" argument(s): \"{0}\"", message), new RuntimeException(message, new RuntimeException(message)));
        return new ErrorRecord(call, "ScriptMethodRuntimeException", ErrorCategory.NotSpecified, null);
    }
}
